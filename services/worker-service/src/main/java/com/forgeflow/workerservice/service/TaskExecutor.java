package com.forgeflow.workerservice.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.forgeflow.workerservice.api.JobApiClient.ExecutionJob;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.time.LocalDate;
import java.time.ZoneId;

@Component("forgeFlowTaskExecutor")
public class TaskExecutor {
    private final ObjectMapper mapper;
    private final Path reportsDir;

    public TaskExecutor(ObjectMapper mapper, @Value("${app.reports-dir:/data/reports}") String dir) {
        this.mapper = mapper;
        this.reportsDir = Path.of(dir).toAbsolutePath().normalize();
    }

    public JsonNode execute(ExecutionJob job) throws Exception {
        JsonNode payload = mapper.readTree(job.payloadJson() == null ? "{}" : job.payloadJson());
        return switch (job.type()) {
            case "GENERATE_REPORT" -> generateReport(job, payload);
            case "SIMULATE_FAILURE" -> simulateFailure(job, payload);
            default -> throw new IllegalArgumentException("Unsupported job type: " + job.type());
        };
    }

    private JsonNode simulateFailure(ExecutionJob job, JsonNode payload) {
        int failFirst = Math.max(0, Math.min(8, payload.path("failFirstAttempts").asInt(2)));
        if (job.attempts() <= failFirst) {
            throw new IllegalStateException("Intentional Failure Lab error on attempt " + job.attempts() + " of " + failFirst);
        }
        ObjectNode result = mapper.createObjectNode();
        result.put("message", "Failure Lab job succeeded after simulated failures");
        result.put("attempts", job.attempts());
        result.put("sample", true);
        return result;
    }

    private JsonNode generateReport(ExecutionJob job, JsonNode payload) throws Exception {
        Files.createDirectories(reportsDir);
        int days = Math.max(1, Math.min(90, payload.path("lookbackDays").asInt(30)));
        String name = job.id() + "-sales-report.csv";
        Path target = reportsDir.resolve(name).normalize();
        if (!target.startsWith(reportsDir)) throw new IllegalArgumentException("Invalid report path");

        long totalOrders = 0, grossTotal = 0, refundTotal = 0;
        StringBuilder csv = new StringBuilder("Record_Type,Job_ID,Data_Label,Date,Order_Count,Gross_Sales_INR,Refunds_INR,Net_Sales_INR,Notes\n");
        csv.append("NOTICE,").append(job.id()).append(",SAMPLE DATA ONLY,,,,,,Illustrative data generated by ForgeFlow demo handler\n");
        LocalDate end = LocalDate.now(ZoneId.of("Asia/Kolkata"));
        LocalDate start = end.minusDays(days - 1L);
        for (int i = 0; i < days; i++) {
            LocalDate date = start.plusDays(i);
            long orders = 20 + (i * 7L) % 37;
            long gross = orders * (1200 + (i * 37L) % 800);
            long refunds = (i * 53L) % 1500;
            long net = gross - refunds;
            totalOrders += orders;
            grossTotal += gross;
            refundTotal += refunds;
            csv.append("DAILY,").append(job.id()).append(",SAMPLE DATA ONLY,").append(date).append(',')
                    .append(orders).append(',').append(gross).append(',').append(refunds).append(',').append(net)
                    .append(",Illustrative values\n");
        }
        csv.append("TOTAL,").append(job.id()).append(",SAMPLE DATA ONLY,").append(start).append(" to ").append(end).append(',')
                .append(totalOrders).append(',').append(grossTotal).append(',').append(refundTotal).append(',')
                .append(grossTotal - refundTotal).append(",Totals for all sample days\n");
        Files.writeString(target, csv.toString(), StandardCharsets.UTF_8, StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING);

        ObjectNode result = mapper.createObjectNode();
        result.put("fileName", name);
        result.put("downloadPath", "/api/jobs/" + job.id() + "/result");
        result.put("sampleData", true);
        result.put("lookbackDays", days);
        result.put("totalOrders", totalOrders);
        result.put("grossSalesInr", grossTotal);
        result.put("refundsInr", refundTotal);
        result.put("netSalesInr", grossTotal - refundTotal);
        return result;
    }
}
